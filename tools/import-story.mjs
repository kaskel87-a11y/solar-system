// Rebuilds missions-data.js from the story pack copied into data/story/ (missions.json + NPC_BARKS.md).
// The game imports missions-data.js; swap the JSON and re-run `node tools/import-story.mjs` to change the story.
import fs from 'node:fs';
const root = new URL('..', import.meta.url).pathname;
const story = JSON.parse(fs.readFileSync(root + 'data/story/missions.json', 'utf8'));
const md = fs.readFileSync(root + 'data/story/NPC_BARKS.md', 'utf8');
// barks: "## Section" headings; "- **Who:** "line" / "line"" or "- "line"" bullets
const barks = {}; let sec = null;
for (const raw of md.split('\n')) {
  const h = /^##\s+(.+)/.exec(raw); if (h) { sec = h[1].trim(); barks[sec] = {}; continue; }
  const b = /^-\s+(?:\*\*(.+?):\*\*\s*)?(.+)$/.exec(raw.trim()); if (!sec || !b) continue;
  const who = b[1] || '_', lines = [...b[2].matchAll(/["“]([^"”]+)["”]/g)].map(m => m[1]);
  if (!lines.length) continue; (barks[sec][who] ||= []).push(...lines);
}
const missions = [];
for (const [name, c] of Object.entries(story.contacts)) for (const m of c.missions) missions.push({ ...m, contactInfo: { name, at: c.at, building: c.building, tier: c.tier, blurb: c.blurb } });
for (const m of story.side_jobs) missions.push({ ...m, side: true });
const out = { format: story.format, buildings: story.proposed_buildings, contacts: Object.fromEntries(Object.entries(story.contacts).map(([k, v]) => [k, { world: v.world, at: v.at, building: v.building, blurb: v.blurb, tier: v.tier }])), missions, barks };
fs.writeFileSync(root + 'missions-data.js', '// GENERATED by tools/import-story.mjs from data/story/. Do not edit by hand.\nexport const STORY = ' + JSON.stringify(out) + ';\n');
console.log(`missions-data.js: ${missions.length} missions, ${Object.keys(out.contacts).length} contacts, ${Object.keys(barks).length} bark sections`);

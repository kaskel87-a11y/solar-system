import * as C from '../mobbosscore.js';
let fails = 0; const ok = (k, c, v) => { if (!c) { fails++; console.log('FAIL', k, v ?? ''); } };
const s = C.fresh();
ok('start thug', C.view(s).name === 'Street Thug' && C.view(s).levelOff === 0);
const a = C.grant(s, 'officer');
ok('officer +4', a.added === 4 && s.respect === 4 && !a.up);
ok('drone +2', C.grant(s, 'drone').added === 2 && s.respect === 6);
ok('car +3', C.grant(s, 'car').added === 3);
while (s.respect < 8) C.grant(s, 'drone');
ok('enforcer', C.tierAt(s.respect).id === 'enforcer' && C.levelOff('enforcer') === 0.15 && C.crewCut('enforcer') === 0);
ok('capo cut', C.crewCut('capo') === 0.1 && C.canHesitate('capo') === false);
ok('underboss hesitates', C.canHesitate('underboss') && C.turfCut('underboss') === 0);
ok('boss turf', C.turfCut('boss') === 0.15 && C.nextAt(70) === null);
const h = C.fresh(); h.respect = 40;
ok('odd raises', C.raiseHeat(h) === true && C.raiseHeat(h) === false && C.raiseHeat(h) === true);
ok('thug always raises', C.raiseHeat(C.fresh()) === true && C.raiseHeat(C.fresh()) === true);
ok('save', C.load(JSON.stringify(s)).respect === s.respect && C.load('nope').respect === 0);
console.log(fails ? fails + ' FAILED' : 'mobboss unit OK');
process.exit(fails ? 1 : 0);

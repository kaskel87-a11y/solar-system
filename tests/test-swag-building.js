// Slick's Planum shop: open-west lobby, buys, wardrobe Yeti, owned board skips rent, ball color,
// liquor / chem veil, insult ban / fine / timeout, shop hidden during bowling / rent / grab,
// door walk and snowboard slide. iPhone 393x852.
// BASE=http://127.0.0.1:8871/ BR=webkit DEV=393x852 ARTIFACTS=/opt/cursor/artifacts node tests/test-swag-building.js
const { chromium, webkit, devices } = require('playwright');
const fs = require('fs'), path = require('path');
const base = process.env.BASE || 'http://127.0.0.1:8871/', BR = process.env.BR || 'webkit', DEV = process.env.DEV || '393x852';
const art = process.env.ARTIFACTS || '/opt/cursor/artifacts';
const sleep = ms => new Promise(r => setTimeout(r, ms));
(async () => {
  fs.mkdirSync(art, { recursive: true });
  const browser = await (BR === 'webkit' ? webkit : chromium).launch({ args: BR === 'chromium' ? ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] : [] });
  const m = /^(\d+)x(\d+)$/.exec(DEV), { defaultBrowserType: _d, ...iph } = devices['iPhone 14'];
  const dev = { ...iph, viewport: { width: +m[1], height: +m[2] }, screen: { width: +m[1], height: +m[2] }, deviceScaleFactor: 2 };
  const ctx = await browser.newContext(dev); await ctx.addInitScript(() => { window.__ssxNoKeepAlive = true; }); const page = await ctx.newPage();
  const errors = []; page.on('pageerror', e => { if (!/audio device/i.test(e.message)) errors.push('PE ' + e.message); }); page.on('console', msg => { if (msg.type() === 'error' && !/audio device|Failed to load resource/i.test(msg.text())) errors.push('CE ' + msg.text().slice(0, 220)); });
  const G = (f, a) => page.evaluate(f, a), bad = [];
  const ok = (k, v, cond) => { if (cond === undefined) cond = v; if (!cond) bad.push(k); console.log(`${cond ? 'PASS' : 'FAIL'} ${k} ${typeof v === 'boolean' ? '' : JSON.stringify(v)}`); };
  const wait = async (f, ms = 30000, a) => { try { await page.waitForFunction(f, a, { timeout: ms, polling: 60 }); return true; } catch (e) { return false; } };
  const shot = async name => { const p = path.join(art, name); await page.screenshot({ path: p, timeout: 120000 }); console.log('SHOT', p); return p; };
  try {
    await page.goto(base + '?look=classic&models=1&t=' + Date.now()); await wait(() => window.__frames > 3 && !document.getElementById('loading'), 120000);
    await G(() => localStorage.clear()); await page.reload(); await wait(() => window.__frames > 3 && !document.getElementById('loading'), 120000);
    await G(() => window.__app.landOn(window.__app.bodies.find(b => b.name === 'Mars').mesh));
    await wait(() => window.__app.state.onSurface && !window.__app.state.transitioning && window.__app.surface.info?.intro === 0, 120000);
    await sleep(800);
    if (await G(() => getComputedStyle(document.getElementById('radio')).display !== 'none')) await G(() => document.getElementById('radioLater')?.click());
    await G(() => { window.__app.surface.world.setWanted(0); window.__app.game?.setAliens?.(false); window.__app.surface.game.progress.credits = 20000; });
    ok('api', await G(() => !!(window.SSX?.swag?.open && window.SSX?.swag?.slide && window.__swag?.core?.SLABS)));
    await G(() => window.__icecap.go('arrive'));
    await wait(() => !!window.__app.surface.scene.getObjectByName('planum-swag'), 15000);
    await sleep(600);
    const shell = await G(() => {
      const g = window.__app.surface.scene.getObjectByName('planum-swag'); let boxes = 0;
      g.traverse(o => { if (o.geometry?.type !== 'BoxGeometry') return; let p = o; while (p) { if (p.userData?.human) return; p = p.parent; } boxes++; });
      const W = window.__swag.core, w = window.__app.surface.world, s = W.SLABS[0];
      return { boxes, solids: !!w.collide(s.x, s.z, 0.15), door: w.collide(63.2, 950, 0.45), jamb: w.collide(W.SLABS.find(q => q.id === 'west-s').x, W.SLABS.find(q => q.id === 'west-s').z, 0.45), place: window.SSX.icecap.place() };
    });
    ok('boxBudget', shell.boxes, shell.boxes > 12 && shell.boxes <= 32);
    ok('solidsUp', shell.solids === true && shell.jamb && !shell.door, shell);
    ok('fastTravelPad', shell.place, Math.hypot(shell.place.x - 44, shell.place.z - 948) < 1);
    await G(() => { const t = document.getElementById('toast'); if (t) t.classList.remove('on'); });
    await G(() => window.__icecap.view({ p: [48, 3.8, 942], l: [72, 3.6, 951] })); await sleep(500);
    await shot('planum-swag-exterior.png');
    await G(() => window.__icecap.view({ p: [59.6, 2.5, 950.8], l: [74, 2.3, 950] })); await sleep(400);
    await shot('planum-swag-entrance.png');
    await G(() => window.__icecap.view(null));
    await G(() => window.__icecap.go('benny')); await sleep(400);
    ok('rentNotShop', await G(() => ({ mode: window.__icecap.ctx()?.mode, shop: document.getElementById('swagPanel')?.classList.contains('on') })), (await G(() => window.__icecap.ctx()?.mode)) === 'rent' && !(await G(() => document.getElementById('swagPanel')?.classList.contains('on'))));
    const act = await G(() => { const a = document.getElementById('icecapAct'), r = a.getBoundingClientRect(); return { on: a.classList.contains('on'), h: r.height, bottom: r.bottom, ih: innerHeight }; });
    ok('actButton', act, act.on && act.h >= 52 && act.bottom < act.ih - 200);
    await wait(() => window.SSX.icecap.state().rivalState === 'hut', 8000);
    if (await G(() => window.SSX.icecap.state().rivalState === 'hut')) {
      await G(() => window.__icecap.rivalHere()); await sleep(400);
      ok('grabNotShop', await G(() => window.__icecap.ctx()?.mode), (await G(() => window.__icecap.ctx()?.mode)) === 'grab');
      ok('shopClosedAtGrab', await G(() => !document.getElementById('swagPanel')?.classList.contains('on')));
    } else ok('grabNotShop', 'no rival this visit', false);
    const spot = await G(() => window.SSX.swag.spot());
    await G(p => window.__app.surface.debugMove(p.x, p.z, Math.PI / 2), spot); await sleep(400);
    ok('swagButton', await G(() => window.__icecap.ctx()?.mode), (await G(() => window.__icecap.ctx()?.mode)) === 'swag');
    await G(() => window.SSX.swag.open()); await sleep(200);
    const buyY = await G(() => window.SSX.swag.buy('yeti'));
    await sleep(300);
    const yeti = await G(() => ({ buy: true, wear: window.SSX.skins.equipped, owned: window.SSX.skins.owned.includes('yeti'), applied: window.SSX.skins.state().applied, label: document.querySelector('#swagPanel .hd small')?.textContent, row: [...document.querySelectorAll('#swagPanel .row')].some(r => /Yeti/.test(r.textContent) && /Wearing/.test(r.textContent)) }));
    ok('buyYeti', buyY, buyY?.ok && yeti.wear === 'yeti' && yeti.owned && yeti.applied === 'yeti' && yeti.row);
    ok('shopWording', yeti.label, /shop/i.test(yeti.label || '') && !/stall/i.test(yeti.label || ''));
    const btn = await G(() => { const b = document.querySelector('#swagPanel button'); const r = b.getBoundingClientRect(); return { h: r.height, w: r.width }; });
    ok('tapTarget', btn, btn.h >= 44 && btn.w >= 44);
    await shot('planum-swag-shop-393.png');
    await G(() => window.SSX.swag.close());
    const board = await G(() => window.SSX.swag.buy('dustrunner'));
    await G(() => window.__icecap.go('benny')); await sleep(350);
    ok('ownedBoardLift', { board, mode: await G(() => window.__icecap.ctx()?.mode) }, board?.ok && (await G(() => window.__icecap.ctx()?.mode)) === 'lift' && (await G(() => window.SSX.swag.hasBoard())) && !(await G(() => window.SSX.swag.needsRent(false))));
    const ball = await G(() => window.SSX.swag.buy('guttergod'));
    await sleep(250);
    ok('ballColor', await G(() => ({ look: window.SSX.swag.ballLook().color, mesh: window.__icecap.parts().ball.material.color.getHex() })), ball?.ok && (await G(() => window.SSX.swag.ballLook().color)) === 0x1a1a1c && (await G(() => window.__icecap.parts().ball.material.color.getHex())) === 0x1a1a1c);
    await G(() => window.__icecap.go('foul')); await sleep(300);
    await G(() => window.SSX.swag.open());
    await G(() => window.SSX.icecap.bowl()); await sleep(400);
    ok('hiddenWhileBowling', await G(() => ({ bowl: document.body.classList.contains('icecapBowling'), panel: getComputedStyle(document.getElementById('swagPanel')).display, chip: getComputedStyle(document.getElementById('swagChip')).display, color: window.__icecap.parts().ball.material.color.getHex() })), (await G(() => document.body.classList.contains('icecapBowling'))) && (await G(() => getComputedStyle(document.getElementById('swagPanel')).display)) === 'none' && (await G(() => window.__icecap.parts().ball.material.color.getHex())) === 0x1a1a1c);
    await G(() => window.__icecap.view({ p: [52, 6.5, 968], l: [40, 1.2, 1002] })); await sleep(400);
    await shot('planum-swag-lane-clear.png');
    await G(() => window.__icecap.view(null));
    await G(() => window.SSX.icecap.roll({ aim: 0, power: 0.7, spin: 0 }));
    await wait(() => !window.SSX.icecap.state().bowl?.rolling, 12000);
    ok('rolledOwnedBall', await G(() => window.SSX.icecap.state().bowl?.rolls?.length) >= 1);
    await G(() => window.SSX.icecap.quit()); await sleep(200);
    ok('shopReturns', await G(() => !document.body.classList.contains('icecapBowling')));
    const chem = await G(() => {
      const a = window.SSX.swag, beer = a.buy('polarlager'), dust = a.buy('reddust');
      const u1 = a.use('polarlager'); a.use('reddust');
      const veil = document.getElementById('swagVeil').className;
      return { beer: beer.ok, dust: dust.ok, u1: u1.ok, veil, chip: document.getElementById('swagChip').textContent };
    });
    ok('liquorChem', chem, chem.beer && chem.dust && chem.u1 && /courage|wobble|buzz/.test(chem.veil));
    const ban = await G(() => {
      const a = window.SSX.swag; a.open(); const said = a.insult('slick');
      const blocked = a.buy('polarlager');
      const chip = document.getElementById('swagChip').textContent;
      const paid = a.payFine();
      const W = window.__swag.core, sample = W.insult(W.fresh(), 'pebble', 1000);
      const save = JSON.parse(localStorage.getItem('ssx.swag.v1'));
      return { said: said.ok, why: blocked.why, chip, paid: paid.ok, clear: !a.state().banned, timeout: !W.banned(sample.state, 1000 + W.BAN_MS), threads: save.threads, boards: save.boards, balls: save.balls, v: save.v };
    });
    ok('insultFine', ban, ban.said && ban.why === 'banned' && /shop/i.test(ban.chip) && ban.paid && ban.clear && ban.timeout && ban.v === 1 && ban.threads.includes('yeti') && ban.boards.includes('dustrunner') && ban.balls.includes('guttergod'));
    await G(() => window.SSX.swag.close());
    await G(() => { window.SSX.icecap.boardOff(); window.__app.surface.debugMove(60.4, 950, -Math.PI / 2); window.__app.keys.KeyW = true; });
    await sleep(1100);
    await G(() => { window.__app.keys.KeyW = false; });
    const walked = await G(() => window.__app.surface.info.x);
    ok('walkThroughDoor', walked, walked > 63);
    await G(() => { window.__app.surface.debugMove(60.4, 946.7, -Math.PI / 2); window.__app.keys.KeyW = true; });
    await sleep(900);
    await G(() => { window.__app.keys.KeyW = false; });
    const jammed = await G(() => window.__app.surface.info.x);
    ok('walkBlockedByJamb', jammed, jammed < 62.6);
    await G(() => { window.__app.surface.debugMove(60.2, 946.7, -Math.PI / 2); window.SSX.icecap.boardOn(); const b = window.__icecap.S.board; b.x = 60.2; b.z = 946.7; b.v = 14; b.head = -Math.PI / 2; b.air = false; });
    await sleep(700);
    const slid = await G(() => window.__icecap.S.board && { x: window.__icecap.S.board.x, z: window.__icecap.S.board.z, mode: window.SSX.icecap.state().mode });
    ok('boardSlidesOnJamb', slid, slid && slid.mode === 'board' && slid.x < 63 && slid.x > 59);
    await G(() => { window.SSX.icecap.boardOff(); window.__app.surface.debugMove(60.2, 950, -Math.PI / 2); window.SSX.icecap.boardOn(); const b = window.__icecap.S.board; b.x = 60.2; b.z = 950; b.v = 12; b.head = -Math.PI / 2; b.air = false; });
    await sleep(800);
    const through = await G(() => window.__icecap.S.board && window.__icecap.S.board.x);
    ok('boardThroughDoor', through, through > 64);
    await G(() => window.SSX.icecap.boardOff());
  } catch (e) { bad.push('EXC ' + e.message); console.log(e.stack || e.message); }
  ok('noErrors', errors.slice(0, 6), errors.length === 0);
  console.log(bad.length ? `FAIL swag-building: ${bad.join(', ')}` : 'ALL PASS swag-building');
  await browser.close();
  process.exit(bad.length ? 1 : 0);
})();

// game.js stepText() adds a progress or hint suffix; keep the useful ones, in plain words
const SUFFIX = [[/\s*\(go inside\)$/, ''], [/\s*\(get inside\)$/, ' Get inside first.'], [/\s*\(in a stolen ride\)$/, ' You must be in a stolen vehicle.'],
  [/\s*\(equip the ([^)]+)\)$/, ' Switch to the $1 first (tap the weapon chip).']];
// -> { text, how, type, known }
// normalised lookup: trimmed, case-insensitive, quotes and whitespace unified (other bots reword source strings; a near-miss still matches)
const norm = t => String(t || '').replace(/[’‘`´]/g, "'").replace(/[“”]/g, '"').replace(/\s+/g, ' ').trim().toLowerCase();
let NORM = null;
function lookup(t) {
  if (HINTS[t]) return HINTS[t];
  if (!NORM) { NORM = new Map(); for (const k of Object.keys(HINTS)) NORM.set(norm(k), HINTS[k]); }
  return NORM.get(norm(t)) || null;
}
// a text that isn't in HINTS (new or reworded at the source) is shown as-is; the "how" line comes from its step type,
// or from a guess on its first words. Never a stale rewrite.
const GUESS = [[/^(win the (fist )?fight|win the bout|fight)\b/, 'duel'], [/^(get in|hop in|jump in)\b/, 'take'], [/^(kill|defeat|destroy|take down|take out|beat|wipe|clear|purge|survive|fight off)\b/, 'defeat'], [/^(race|win the race|drive through)\b/, 'race'],
  [/^(collect|pick up|gather|grab (all|every|the \d)|scan (all|every|\d))\b/, 'collect'], [/^(return|bring .* back|head back|go back)\b/, 'return'],
  [/^(enter|get inside|go inside|break into)\b/, 'enter'], [/^(steal|take a|jack|hijack|grab a (car|ride|buggy|vehicle))\b/, 'take'],
  [/^(lose|shake|ditch) (the |your )?(heat|cops|stars|wanted)/, 'clean'], [/^((find and )?crack|open the safe)\b/, 'crack'], [/^(hold|defend|stay)\b/, 'hold'], [/^(choose|decide|pick (one|a side))\b/, 'choice'],
  [/^(escort|follow .* to|walk .* to safety)\b/, 'escort'], [/^(buy|purchase)\b/, 'buy'], [/^(pay)\b/, 'pay'],
  [/^(go|head|drive|walk|sneak to|find|reach|get to|meet|talk|visit|deliver|drop|meet|track|locate|follow)\b/, 'goto']];
export function guessType(t) { const n = norm(t); for (const [re, ty] of GUESS) if (re.test(n)) return ty; return null; }
export function plainStep(raw, type) {
  const orig = String(raw ?? '');
  try {
    let t = orig.trim(), tail = '', count = '';
    const m = /\s*\((\d+%|\d+\/\d+)\)$/.exec(t); if (m) { count = ` (${m[1]})`; t = t.slice(0, m.index); }
    for (const [re, rep] of SUFFIX) { const s = re.exec(t); if (s) { tail = s[0].replace(re, rep); t = t.slice(0, s.index); break; } }
    const h = lookup(t);
    if (!h) { const ty = (type && HOW[type]) ? type : guessType(t); return { text: orig, how: (ty && HOW[ty]) || '', type: ty, known: false }; }
    return { text: h[0] + count + tail, how: HOW[h[1]] || '', type: h[1], known: true };
  } catch (e) { return { text: orig, how: '', type: null, known: false }; }
}
